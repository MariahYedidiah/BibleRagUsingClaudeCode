"""Structured records passed between agents. Every agent output is validated against these.

Missing data is explicit: list it in `missing` with a reason instead of inventing it.
"""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

Source = Literal["oshb_wlc", "lxx_swete", "sblgnt", "web"]
CANON_REF = r"^[1-4A-Z][A-Z0-9]{2}\.\d+\.\d+$"


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class TextEntry(Strict):
    """One rendering of a passage.

    original                 Hebrew/Greek source text, quoted from the verse store
    established_translation  a published translation (WEB), quoted from the verse store
    machine_translation      generated by a translation skill; never presented as scripture
    """
    kind: Literal["original", "established_translation", "machine_translation"]
    source: Source
    language: Literal["he", "grc", "en"]
    text: str = Field(min_length=1)
    verse_uid: str | None = None   # required for quoted text
    excerpt: bool = False          # quoted text is a contiguous part of the verse, not all of it
    translates: str | None = None  # machine_translation: verse_uid of the original it renders
    translator: str | None = None  # machine_translation: e.g. "claude:claude-opus-5-5"
    notes: str | None = None

    @model_validator(mode="after")
    def _kind_fields(self):
        if self.kind == "machine_translation":
            if not self.translator or not self.translates:
                raise ValueError("machine_translation needs `translator` and `translates`")
            if self.verse_uid:
                raise ValueError("machine_translation is not stored text; use `translates`, not `verse_uid`")
        elif not self.verse_uid:
            raise ValueError(f"{self.kind} text must cite its `verse_uid`")
        return self


class CrossRef(Strict):
    to: str = Field(pattern=CANON_REF)
    relation: Literal["verified", "possible_allusion", "thematic"]
    dataset: str | None = None  # e.g. "openbible"; required for verified
    votes: int | None = None
    note: str | None = None

    @model_validator(mode="after")
    def _verified_needs_dataset(self):
        if self.relation == "verified" and not self.dataset:
            raise ValueError("a verified cross-reference must name its dataset")
        return self


class Missing(Strict):
    field: str
    reason: str


class Passage(Strict):
    canon_ref: str = Field(pattern=CANON_REF)
    display_ref: str              # e.g. "John 1:1"
    testament: Literal["OT", "NT", "DC"]
    alignment: Literal["mapped", "partial", "unmapped"]
    texts: list[TextEntry] = Field(min_length=1)
    retrieval: dict | None = None  # ranks, scores and which query/method found it
    cross_refs: list[CrossRef] = []
    missing: list[Missing] = []


class Confidence(Strict):
    level: Literal["high", "medium", "low", "insufficient"]
    basis: str                    # which measured signals the level rests on
    signals: dict = {}


class PassageTranslation(Strict):
    """Output of the hebrew-to-english and greek-to-english skills."""
    canon_ref: str = Field(pattern=CANON_REF)
    verse_uid: str
    source: Literal["oshb_wlc", "lxx_swete", "sblgnt"]
    corpus_label: Literal["Hebrew (OSHB/WLC)", "Septuagint Greek (Swete LXX)",
                          "New Testament Greek (SBLGNT)"]
    original: str                  # copied verbatim from `bible-rag verse`
    translation: str = Field(min_length=1)
    method: Literal["machine"] = "machine"
    translator: str = Field(pattern=r"^claude:\S+$")
    literal_notes: list[str] = []  # word-level renderings worth showing
    uncertainties: list[str] = []  # variants, idioms, ambiguous grammar
    web_reference: str | None = None  # verse_uid of the WEB verse shown for comparison
    differences_from_web: list[str] = []


class QueryTerm(Strict):
    term: str = Field(min_length=1)  # surface form as it appears in the corpus
    gloss: str
    hits: int = Field(ge=0)          # verses containing it, from `bible-rag terms`


class QueryTerms(Strict):
    """Output of the english-to-hebrew and english-to-greek skills: search terms, never scripture."""
    query: str
    language: Literal["he", "grc"]
    corpus: Literal["oshb_wlc", "lxx_swete", "sblgnt", "lxx_swete+sblgnt"]
    terms: list[QueryTerm] = Field(min_length=1)
    lexical_queries: list[str] = Field(min_length=1)  # pass to `bible-rag search --lexical`
    method: Literal["machine"] = "machine"
    translator: str = Field(pattern=r"^claude:\S+$")
    display: Literal[False] = False  # these terms are never shown as scripture
    notes: list[str] = []


class SkillError(Strict):
    error: Literal["empty_input", "unknown_reference", "wrong_language", "no_terms_found",
                   "check_failed"]
    message: str
    input: str


class Answer(Strict):
    question: str
    answer: str                   # markdown shown to the user
    passages: list[Passage]
    confidence: Confidence
    clarifying_question: str | None = None
